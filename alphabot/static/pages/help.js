// 有序列表：每项可以是字符串或节点
function ol_(...items) { return h("ol", {}, items.map((x) => h("li", {}, x))); }

export async function renderHelp(root, id, alive) {
  const m = await api("/api/method");
  if (!alive()) return;
  const idx = Math.max(0, SECTIONS.findIndex((s) => s[0] === id));
  const [sid, title, lede, build] = SECTIONS[idx];
  const side = h("aside", { class: "side", "aria-label": "帮助目录" },
    h("h3", {}, "使用说明"),
    SECTIONS.map(([k, t]) => h("a", { href: `#/help/${k}`, "aria-current": k === sid ? "true" : null }, t)));
  const prev = SECTIONS[idx - 1]; const next = SECTIONS[idx + 1];
  const pager = h("div", { class: "help-pager" },
    prev ? h("a", { href: `#/help/${prev[0]}` }, `← ${prev[1]}`) : h("span", {}),
    next ? h("a", { href: `#/help/${next[0]}` }, `${next[1]} →`) : h("span", {}));
  fill(root, h("div", { class: "with-side" }, side,
    h("article", { class: "prose" },
      h("h1", {}, title),
      h("p", { class: "lede" }, lede),
      ...build(m),
      pager)));
  window.scrollTo({ top: 0 });
}
